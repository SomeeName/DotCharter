using System.Globalization;
using System.Text;

namespace DotCharter.Tests.Infrastructure;

/// <summary>
///     A complexity budget for every method, accessor and operator in the product tree,
///     measured by <see cref="MethodComplexityMeter" /> (syntax-only Roslyn, so the
///     numbers depend on nothing but the source). <see cref="SourceFileSizeBudgetTests" />
///     stops a FILE from growing; this stops the 400-line method and the 40-branch walk
///     inside it.
///     <para>
///         <b>The budget</b> is McCabe cyclomatic complexity <see cref="CyclomaticBudget" />
///         (CA1502's default) and <see cref="LineBudget" /> physical lines. A member over
///         either fails, unless it is on the hotspot list
///         (<c>MethodComplexityBudgetTests.Hotspots.cs</c>), which holds every member that
///         was over when the budget landed (#837), with its measured value as its ceiling.
///     </para>
///     <para>
///         <b>The list may only shrink.</b> A listed member may not grow past its ceiling;
///         when it shrinks by more than the slack, lower its numbers; when it comes inside
///         the budget, or is deleted or renamed, delete its row. Never add a row or raise a
///         number to turn the gate green — extract a method or a type, or replace a branch
///         ladder with a table.
///     </para>
///     <para>
///         <b>Excluded</b> (<see cref="Excluded" />): the code
///         <c>.claude/rules/tool-selection.md</c> § Simplification limits keeps out of any
///         clean-up pass — Vulkan, per-frame rendering, DSP, the native engine's managed
///         edge — plus every <c>unsafe</c> member and generated file. Each entry says why
///         and must still match a file.
///     </para>
///     <para>
///         Regenerate the measurement with <c>DOTCHARTER_COMPLEXITY_REPORT=&lt;file outside
///         the repo&gt;</c> and <c>Invoke-Gate.ps1 -FilterClass "*MethodComplexityBudgetTests"</c>:
///         <see cref="WriteReport" /> writes every member over half the budget, worst
///         first, and the rows the hotspot list would hold today.
///     </para>
/// </summary>
public sealed partial class MethodComplexityBudgetTests
{
    public const int CyclomaticBudget = 25;

    public const int LineBudget = 150;

    private const int CyclomaticSlack = 2;

    private const int LineSlack = 10;

    private sealed record Exclusion(string PathPrefix, string Reason);

    private sealed record Hotspot(string Key, int Cyclomatic, int Lines);

    private static readonly Exclusion[] Excluded =
    [
        new("DotCharter.Rendering/", "Vulkan synchronization and lifetime, and the per-frame 3D/2D render path"),
        new("DotCharter.UI/Graphics/", "the composed-Vulkan 2D compositor: swapchain and image-pool lifetime"),
        new("DotCharter.UI/Controls/Timeline2D/", "the Vulkan timeline backend"),
        new("DotCharter.UI/Controls/ChartRenderer", "the composed-Vulkan timeline's frame content, split only when the owner asks"),
        new("DotCharter.UI/Controls/Preview3DRenderDriver.cs", "the 3D render-loop thread and its swapchain lifetime"),
        new("DotCharter.UI/Controls/Layers/", "the 2D highway's per-frame drawing: perf-critical loops"),
        new("DotCharter.Analysis/", "audio-to-chart DSP cores under a determinism contract"),
        new("DotCharter.Tone/Audio/JuceAudioPlaybackService", "the native engine's managed edge: one handle under one _gate, replayed on rebuild"),
        new("DotCharter.Tone/Audio/Dsp/DspNativeInterop.cs", "the rig's P/Invoke edge"),
        new("DotCharter.Tone/Audio/Dsp/Spectrum/", "spectrum DSP"),
        new("DotCharter.Tone/Audio/Dsp/Loudness/", "loudness DSP (integrated LUFS)"),
        new("DotCharter.Tone/Audio/Tuner/", "the managed tuner's pitch DSP (MPM)"),
        new("DotCharter.Services/Audio/Tuning/", "the live tuner's pitch filter over the detector"),
        new("DotCharter.Services/Audio/LivePlay/", "live note detection over the capture stream: per-hop CQT, onset and pitch DSP"),
        new("DotCharter.Core/Utilities/LearnedChordFingeringData.cs", "generated by tools/chart-eval --learn, never hand-edited"),
    ];

    [Fact]
    public void NoMemberOutgrowsItsBudget()
    {
        var ceilings = Hotspots.ToDictionary(h => h.Key, StringComparer.Ordinal);
        var failures = new List<string>();

        foreach (var m in MeasureProduct())
        {
            var ceiling = ceilings.TryGetValue(m.Key, out var hotspot)
                ? hotspot
                : new Hotspot(m.Key, CyclomaticBudget, LineBudget);
            if (m.Cyclomatic > ceiling.Cyclomatic || m.Lines > ceiling.Lines)
            {
                failures.Add($"{m.Key}: cyclomatic {m.Cyclomatic} (budget {ceiling.Cyclomatic}), " +
                             $"{m.Lines} lines (budget {ceiling.Lines})");
            }
        }

        Assert.True(failures.Count == 0, LintReport.Of(
            "these members outgrew their complexity budget",
            failures,
            "extract a method or a type, use guard clauses, or replace a branch ladder with a table; " +
            "never add a hotspot row or raise a ceiling",
            "DotCharter.Tests/Infrastructure/MethodComplexityBudgetTests.cs"));
    }

    [Fact]
    public void EveryHotspotIsStillNeededAndTight()
    {
        var measured = MeasureProduct().ToDictionary(m => m.Key, StringComparer.Ordinal);
        var failures = new List<string>();

        foreach (var hotspot in Hotspots)
        {
            if (!measured.TryGetValue(hotspot.Key, out var m))
            {
                failures.Add($"{hotspot.Key}: no such member any more (deleted, renamed or excluded) — delete the row");
                continue;
            }

            if (m.Cyclomatic <= CyclomaticBudget && m.Lines <= LineBudget)
            {
                failures.Add($"{hotspot.Key}: cyclomatic {m.Cyclomatic}, {m.Lines} lines is inside the budget — delete the row");
            }
            else if (Ceiling(m.Cyclomatic, CyclomaticBudget) + CyclomaticSlack < hotspot.Cyclomatic
                     || Ceiling(m.Lines, LineBudget) + LineSlack < hotspot.Lines)
            {
                failures.Add($"{hotspot.Key}: now {Row(m)} — lower the row to that");
            }
        }

        Assert.True(failures.Count == 0, LintReport.Of(
            "the hotspot list may only shrink, and its numbers follow the code down",
            failures,
            "apply each instruction to MethodComplexityBudgetTests.Hotspots.cs",
            "DotCharter.Tests/Infrastructure/MethodComplexityBudgetTests.cs"));
    }

    [Fact]
    public void EveryHotspotIsListedOnceAndEveryExclusionStillMatches()
    {
        Assert.Equal(Hotspots.Length, Hotspots.Select(h => h.Key).Distinct(StringComparer.Ordinal).Count());
        Assert.All(Hotspots, h => Assert.True(h.Cyclomatic > CyclomaticBudget || h.Lines > LineBudget, h.Key));
        Assert.All(Hotspots, h => Assert.True(h.Cyclomatic >= CyclomaticBudget && h.Lines >= LineBudget, h.Key));
        Assert.All(Excluded, e => Assert.False(string.IsNullOrWhiteSpace(e.Reason), e.PathPrefix));
        Assert.DoesNotContain(Hotspots, h => IsExcluded(h.Key));

        var files = ProductSourceFiles(TestPaths.RepoRoot()).Select(f => f.Relative).ToList();
        Assert.All(Excluded, e => Assert.Contains(files, f => f.StartsWith(e.PathPrefix, StringComparison.Ordinal)));
    }

    [Fact]
    public void TheScanSeesTheProductTree()
    {
        var keys = MeasureProduct().Select(m => m.Key).ToHashSet(StringComparer.Ordinal);

        Assert.True(keys.Count > 10_000, $"only {keys.Count} members measured; the scan is broken");
        Assert.Contains(keys, k => k.StartsWith("DotCharter.Services/Parsing/GuitarPro/GpNoteParser.cs::", StringComparison.Ordinal));
        Assert.Contains(keys, k => k.StartsWith("DotCharter.UI/", StringComparison.Ordinal));
        Assert.DoesNotContain(keys, k => k.StartsWith("DotCharter.Tests/", StringComparison.Ordinal));
        Assert.DoesNotContain(keys, k => k.StartsWith("DotCharter.Rendering/", StringComparison.Ordinal));
        Assert.DoesNotContain(keys, k => k.Contains("/obj/", StringComparison.Ordinal));
    }

    [Fact]
    public void WriteReport()
    {
        var target = Environment.GetEnvironmentVariable("DOTCHARTER_COMPLEXITY_REPORT");
        if (string.IsNullOrEmpty(target))
            Assert.Skip("DOTCHARTER_COMPLEXITY_REPORT is not set");

        var all = MeasureProduct().ToList();
        var report = new StringBuilder();
        report.AppendLine("cyclomatic\tlines\tnesting\tmember");
        foreach (var m in all.Where(m => m.Cyclomatic > CyclomaticBudget / 2 || m.Lines > LineBudget / 2)
                     .OrderByDescending(m => m.Cyclomatic).ThenByDescending(m => m.Lines))
        {
            report.AppendLine(CultureInfo.InvariantCulture, $"{m.Cyclomatic}\t{m.Lines}\t{m.Nesting}\t{m.Key}");
        }

        report.AppendLine().AppendLine("// hotspot rows");
        foreach (var m in all.Where(m => m.Cyclomatic > CyclomaticBudget || m.Lines > LineBudget)
                     .OrderBy(m => m.Key, StringComparer.Ordinal))
        {
            report.AppendLine(CultureInfo.InvariantCulture, $"        new(\"{m.Key}\", {Row(m)}),");
        }

        File.WriteAllText(target, report.ToString());
    }

    private static string Row(MethodComplexityMeter.Measurement m) =>
        $"{Ceiling(m.Cyclomatic, CyclomaticBudget)}, {Ceiling(m.Lines, LineBudget)}";

    private static int Ceiling(int measured, int budget) => Math.Max(measured, budget);

    /// <summary>Four facts read the same measurements; the product tree is parsed once
    /// per process, not once per fact.</summary>
    private static readonly Lazy<MethodComplexityMeter.Measurement[]> Product = new(() => [.. MeasureTree()]);

    private static IEnumerable<MethodComplexityMeter.Measurement> MeasureProduct() => Product.Value;

    private static IEnumerable<MethodComplexityMeter.Measurement> MeasureTree()
    {
        foreach (var (full, relative) in ProductSourceFiles(TestPaths.RepoRoot()))
        {
            if (IsExcluded(relative))
                continue;

            var source = File.ReadAllText(full);
            if (source.TrimStart('﻿').StartsWith("// <auto-generated", StringComparison.Ordinal))
                continue;

            foreach (var m in MethodComplexityMeter.Measure(relative, source))
                yield return m;
        }
    }

    private static bool IsExcluded(string relativeOrKey) =>
        Excluded.Any(e => relativeOrKey.StartsWith(e.PathPrefix, StringComparison.Ordinal));

    private static IEnumerable<(string Full, string Relative)> ProductSourceFiles(string root)
    {
        foreach (var project in Directory.EnumerateDirectories(root, "DotCharter.*"))
        {
            if (Path.GetFileName(project) == "DotCharter.Tests")
                continue;

            foreach (var file in Directory.EnumerateFiles(project, "*.cs", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (relative.Contains("/bin/", StringComparison.Ordinal) || relative.Contains("/obj/", StringComparison.Ordinal))
                    continue;

                yield return (file, relative);
            }
        }
    }
}
