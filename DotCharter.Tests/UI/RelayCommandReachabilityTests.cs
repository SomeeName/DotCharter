using System.Text.RegularExpressions;

namespace DotCharter.Tests.UI;

/// <summary>
///     A <c>[RelayCommand]</c> whose generated <c>…Command</c> property is bound by
///     no view and invoked by no code is a button that cannot be pressed.
///
///     <para>
///         This repo has shipped that shape four times — the 0.22 power tools,
///         couch co-op's entry point, the whole ABI v28 per-player rig
///         (<c>CoopRigApplier</c>, registered and resolved by nothing for a
///         release), and <c>RsTonePlaybackCoordinator.ActiveToneChanged</c>, which
///         had no consumer in the entire UI project. Each time the remedy was the
///         same and each time it was written by hand for that one feature:
///         <c>CoopReachabilityTests</c>, <c>PowerToolReachabilityTests</c>,
///         <c>TonePreviewReachabilityTests</c>. This is the general case.
///     </para>
///     <para>
///         <b>It is a source lint, deliberately.</b> The command is generated by a
///         source generator from the attribute, so reflection would happily find a
///         property that nothing on earth invokes — which is exactly the state
///         being looked for. What matters is whether a HUMAN-authored file names
///         it: markup that binds it, or code that executes it.
///     </para>
///     <para>
///         <b>It matches on the bare NAME, so it under-reports.</b> A binding is
///         <c>{Binding SearchCommand}</c> against an implicit DataContext — the
///         markup never says which view model that is — so a dead
///         <c>SearchCommand</c> on one view model is satisfied by a live
///         <c>SearchCommand</c> on another. This lint therefore proves a command
///         IS dead, never that one is alive.
///     </para>
///     <para>
///         The worked example, and the reason that caveat matters:
///         <c>NamCaptureBrowserViewModel</c> — 713 lines of TONE3000 capture
///         browsing — was constructed and exposed as
///         <c>PresetBrowserViewModel.NamBrowser</c> with NO markup binding it,
///         yet only four of its ten commands showed up here. The other six
///         (<c>Search</c>, <c>SignIn</c>, <c>SignOut</c>, <c>Download</c>,
///         <c>Delete</c>, <c>SaveClientId</c>) collide by name with live commands
///         on the Songsterr dialogs, the online panel and the stem-model tab, and
///         read as reachable while nothing reached THEM. The whole panel had been
///         gone since v0.43 deleted <c>PedalboardView.axaml</c>, and its rail row
///         went on opening an empty grid. **It was restored into
///         <c>AmpFxRigView</c> in 0.57**, which is why its four commands are no
///         longer listed below.
///         <b>The lesson stands: four entries here were the visible tip of a
///         missing feature.</b> When several dead commands share a view model,
///         check whether the whole surface is gone before treating them as
///         leftovers.
///     </para>
/// </summary>
public sealed class RelayCommandReachabilityTests
{
    /// <summary>
    ///     Commands that are unreachable TODAY, each of which is either dead code
    ///     or a feature whose entry point was never drawn. **Do not add to this
    ///     list to make a new command pass** — that is the whole failure mode it
    ///     exists to stop. Delete an entry by wiring the command up or by removing
    ///     it.
    ///     <para>
    ///         <b>There is a THIRD verdict besides "wire it" and "delete it", and
    ///         it took six entries off this list in 0.58: the generated WRAPPER is
    ///         the dead part and the method is live.</b>
    ///         <c>AddGuitarVstFromSelection</c>, <c>Join</c>,
    ///         <c>RefreshLivePlayersAsync</c>, <c>RefreshPreview</c>,
    ///         <c>Revalidate</c> and <c>TriageFilter</c> are each called directly
    ///         by C# — a property-changed handler, a sibling partial, a
    ///         <c>PointerPressed</c> handler on a tile that is a <c>Border</c>
    ///         rather than a <c>Button</c> — while their <c>…Command</c>
    ///         properties were bound by nothing. Dropping the attribute is the
    ///         whole fix; deleting the method would have broken a live surface.
    ///         The tell is that the SAME FILE names the method, which this lint
    ///         cannot count as reachability (it excludes same-file references, and
    ///         has to: a command's own declaration always mentions it).
    ///     </para>
    ///     <para>
    ///         <b>A note excusing an entry as "a feature, not a leftover" ROTS,
    ///         and then it protects dead code.</b> This summary used to say
    ///         <c>ToggleBypassCommand</c> was the only per-pedal bypass and that a
    ///         single pedal could not be bypassed from the UI at all. That stopped
    ///         being true in 0.57, when the restored <c>AmpFxRigView</c> gave every
    ///         unit foot a <c>ToggleButton IsChecked="{Binding Bypassed}"</c> —
    ///         two-way by default, writing the same property the command wrote. It
    ///         also excused <c>SetActiveCommand</c> as "shadowed by" the stem-model
    ///         row's <c>IsActive</c> binding, when <i>shadowed by</i> is the
    ///         definition of superseded; that one is deleted.
    ///     </para>
    ///     <para>
    ///         <b>What is left, and why (0.58, minus one in 0.59).</b>
    ///         <c>ClearCommand</c> was the entry point this list called "a real
    ///         missing entry point, wanted beside <c>PickFileCommand</c>", and it
    ///         is now drawn: a ✕ beside Choose on BOTH file-param faces
    ///         (<c>RigCardFileClear</c> on the board card's load strip,
    ///         <c>RigDockFileClear</c> in the dock's capture column), visible only
    ///         while a file is loaded. Five of the remaining seven sit in
    ///         <c>PedalboardViewModel*</c> / <c>AmpFxRigView.axaml</c>, which an
    ///         adjacent change owned while the 0.58 pass ran, and were left alone
    ///         deliberately: <c>MoveUp</c>/<c>MoveDownCommand</c>
    ///         (superseded by <c>MoveTo</c> + <c>RigBoardDragController</c>, the
    ///         same call already made for the VST slot pair),
    ///         <c>ToggleBypassCommand</c> (superseded, see above),
    ///         <c>ToggleGearRailCommand</c> (the gear panel is hard-pinned visible;
    ///         no GEAR button exists) and <c>ToggleMuteCommand</c> (on
    ///         <c>RegionRowViewModel</c> — the whole split-lane board projection
    ///         outlived the view that drew it). <c>StartPracticeItemCommand</c> left
    ///         the list on 2026-09-19 with the practice queue it started.
    ///         <c>MoveUp</c>/<c>MoveDownCommand</c> and <c>ToggleBypassCommand</c>
    ///         left it on 2026-09-27: the unit's right-click menu
    ///         (<c>RigUnitContextMenu</c>) is built over them.
    ///     </para>
    ///     <para>
    ///         <b>One left in 0.61: <c>RigTunerViewModel</c>'s
    ///         <c>ToggleCommand</c>, deleted.</b> This list excused it as "the
    ///         small half" of a tuner whose <c>SetSurfaceLive</c> "is called by
    ///         no view either, so its poll can never start" — and that claim had
    ///         rotted: <c>AmpFxRigView</c> has reported its own surface liveness
    ///         since 2026-08-15, and the footer needle polls. What was left was
    ///         a toggle for a PANEL that no longer exists (the rig draws the
    ///         tuner permanently), so neither the wrapper nor the method had a
    ///         caller. The method went with the command. <b>An entry's excuse is
    ///         exactly as perishable as any other safety claim in this repo —
    ///         re-read it against code before trusting it.</b>
    ///     </para>
    /// </summary>
    private static readonly HashSet<string> KnownUnreachable = new(StringComparer.Ordinal)
    {
        "ToggleGearRailCommand",
        "ToggleMuteCommand"
    };

    [Fact]
    public void EveryRelayCommand_IsBoundByAViewOrInvokedByCode()
    {
        var sources = ProductSources().ToList();
        var texts = sources.ToDictionary(p => p, File.ReadAllText, StringComparer.OrdinalIgnoreCase);

        var unreachable = new List<string>();

        foreach (var (path, text) in texts)
        {
            if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) continue;

            foreach (var command in CommandsDeclaredIn(text))
            {
                var referencedElsewhere = texts.Any(kv =>
                    !string.Equals(kv.Key, path, StringComparison.OrdinalIgnoreCase) &&
                    kv.Value.Contains(command, StringComparison.Ordinal));

                if (!referencedElsewhere) unreachable.Add($"{command}  ({Path.GetFileName(path)})");
            }
        }

        var names = unreachable
            .Select(u => u.Split("  ", StringSplitOptions.None)[0])
            .ToHashSet(StringComparer.Ordinal);

        // A NEW one is the failure this exists for.
        var fresh = unreachable.Where(u => !KnownUnreachable.Contains(u.Split("  ")[0])).ToList();
        Assert.True(fresh.Count == 0,
            "These [RelayCommand]s are bound by no view and invoked by no code — a button that cannot be " +
            "pressed, which this repo has shipped four times:\n  " + string.Join("\n  ", fresh) +
            "\n\nWire it to the surface that should raise it, or delete it. Do NOT add it to " +
            nameof(KnownUnreachable) + " — that list only ever shrinks.");

        // …and the list only ever shrinks: an entry that became reachable must be
        // deleted, or the next dead command can hide behind it.
        var stale = KnownUnreachable.Where(k => !names.Contains(k)).ToList();
        Assert.True(stale.Count == 0,
            "These are listed as unreachable but something reaches them now — delete them from " +
            nameof(KnownUnreachable) + ":\n  " + string.Join("\n  ", stale));
    }

    /// <summary>
    ///     Commands whose ONLY cross-file references are UNQUALIFIED — files
    ///     that name the command but never the view model that declares it (and
    ///     no dotted member path resolves to it), so the name-match above may
    ///     be satisfied by a same-named command on a DIFFERENT view model (the
    ///     NamCaptureBrowser failure mode: six dead commands read as reachable
    ///     because live Songsterr/online/stem commands shared their names).
    ///     <para>
    ///         The first qualified pass (P2-14) surfaced seven; five got a real
    ///         verdict on the spot — <c>RigTunerViewModel.Open/Close</c>,
    ///         <c>KeybindSettingsViewModel.Open</c> and
    ///         <c>SongBrowserViewModel.Activate</c> were the third verdict
    ///         (method live via a direct C# call, wrapper dead — attribute
    ///         dropped), and <c>ProfileViewModel.RefreshCommand</c> was
    ///         genuinely DEAD (no surface at all; ProfileView now draws its
    ///         refresh). The two below are deferred, each with its reason.
    ///         <b>This list only ever shrinks</b> — resolve the verdict and
    ///         delete the entry; a NEW ambiguous command fails the fact below,
    ///         so a dead command can no longer hide behind a live namesake.
    ///     </para>
    /// </summary>
    private static readonly HashSet<string> KnownAmbiguous = new(StringComparer.Ordinal)
    {
        // CommandPaletteViewModel's. Almost certainly the third verdict (the
        // method is live: Toggle same-file, MainWindow.Input.cs calls Close()
        // directly; no markup binds the wrapper) — but the FILE is owned by a
        // concurrent palette pass, so the de-attribute is deferred to that
        // merge rather than hand-edited under it.
        "CloseCommand"
        // (PedalModelSelectorViewModel's SelectCommand left on 2026-09-27: the
        // mic placement's cards bind a RigMicChoice.SelectCommand, qualified.)
    };

    /// <summary>
    ///     The PRECISION half (P2-14). The fact above proves a command is DEAD;
    ///     this one refuses the opposite lie — "reachable" proven only by a
    ///     same-named command on another view model. A reference is QUALIFIED
    ///     when the referencing file also names the declaring type (a view's
    ///     <c>x:DataType</c>, a template's, or a typed C# use). Commands whose
    ///     only references are unqualified must be in
    ///     <see cref="KnownAmbiguous" /> — evaluated by hand, and the
    ///     list only shrinks.
    /// </summary>
    [Fact]
    public void EveryReachableCommand_IsReachedByAFileThatNamesItsViewModel()
    {
        var sources = ProductSources().ToList();
        var texts = sources.ToDictionary(p => p, File.ReadAllText, StringComparer.OrdinalIgnoreCase);

        // Property/field name → the view-model type(s) it is declared as, over
        // the whole product. This is what makes a DOTTED binding count: markup
        // like `{Binding Dialogs.PatternBuilder.OpenCommand}` never spells the type,
        // but `PatternBuilder` is declared `PatternBuilderDialogViewModel PatternBuilder` on the
        // dialog service, which pins WHICH OpenCommand it is.
        var membersByName = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var (path, text) in texts)
        {
            if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) continue;
            foreach (Match m in Regex.Matches(text, @"\b(\w+ViewModel)\??\s+(\w+)\s*(?:\{|=>|;|=)"))
            {
                if (!membersByName.TryGetValue(m.Groups[2].Value, out var set))
                    membersByName[m.Groups[2].Value] = set = new HashSet<string>(StringComparer.Ordinal);
                set.Add(m.Groups[1].Value);
            }
        }

        var ambiguous = new List<string>();
        var ambiguousNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (var (path, text) in texts)
        {
            if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) continue;

            var declaringTypes = TypesDeclaredIn(text).ToHashSet(StringComparer.Ordinal);
            if (declaringTypes.Count == 0) continue;

            foreach (var command in CommandsDeclaredIn(text))
            {
                if (KnownUnreachable.Contains(command)) continue; // already reported as dead

                var references = texts.Where(kv =>
                        !string.Equals(kv.Key, path, StringComparison.OrdinalIgnoreCase) &&
                        kv.Value.Contains(command, StringComparison.Ordinal))
                    .ToList();
                if (references.Count == 0) continue; // the lenient fact owns this case

                var names = declaringTypes.Concat(ContractsImplementedIn(text)).ToList();
                var qualified = references.Any(kv =>
                    // (a) the referencing file names the declaring type itself
                    // (a view's x:DataType, a template's, a typed C# use), or a
                    // screen CONTRACT that type implements — which is what a
                    // migrated tab's x:DataType names…
                    names.Any(t => kv.Value.Contains(t, StringComparison.Ordinal))
                    // (b) …or it reaches the command through a dotted member
                    // whose declared type IS the declaring view model.
                    || Regex.Matches(kv.Value, $@"(\w+)\.{Regex.Escape(command)}\b")
                        .Any(m => membersByName.TryGetValue(m.Groups[1].Value, out var types)
                                  && types.Overlaps(declaringTypes)));
                if (qualified) continue;

                ambiguous.Add($"{command}  ({Path.GetFileName(path)})");
                ambiguousNames.Add(command);
            }
        }

        var fresh = ambiguous
            .Where(a => !KnownAmbiguous.Contains(a.Split("  ")[0]))
            .ToList();
        Assert.True(fresh.Count == 0,
            "These [RelayCommand]s look reachable ONLY through files that never name their view model — " +
            "the reference may belong to a same-named command on a different type (the " +
            "NamCaptureBrowser failure mode). Check each honestly: if it is genuinely bound, qualify " +
            "the binding (x:DataType) or add it to " + nameof(KnownAmbiguous) + " with the " +
            "evidence; if nothing reaches it, wire it or delete it:\n  " + string.Join("\n  ", fresh));

        var stale = KnownAmbiguous.Where(k => !ambiguousNames.Contains(k)).ToList();
        Assert.True(stale.Count == 0,
            "These are listed as ambiguous-but-real but are now reached by a QUALIFIED reference — " +
            "delete them from " + nameof(KnownAmbiguous) + ":\n  " + string.Join("\n  ", stale));
    }

    /// <summary>Every class/record name a file declares — the vocabulary a
    /// QUALIFIED reference must use. Multiple types per file are normal
    /// (item view models beside their owner).</summary>
    private static IEnumerable<string> TypesDeclaredIn(string text)
    {
        foreach (Match m in Regex.Matches(
                     text, @"(?:class|record)\s+(\w+)"))
        {
            yield return m.Groups[1].Value;
        }
    }

    /// <summary>
    ///     The generated property name for every <c>[RelayCommand]</c> in a file.
    ///     CommunityToolkit drops a trailing <c>Async</c> and appends
    ///     <c>Command</c>, so <c>RefreshLivePlayersAsync</c> generates
    ///     <c>RefreshLivePlayersCommand</c>.
    /// </summary>
    private static IEnumerable<string> CommandsDeclaredIn(string text)
    {
        foreach (Match m in Regex.Matches(
                     text,
                     @"\[RelayCommand[^\]]*\]\s*(?:private|public|internal|protected)[^\r\n]*?\s(\w+)\s*\("))
        {
            var method = m.Groups[1].Value;
            if (method.EndsWith("Async", StringComparison.Ordinal))
                method = method[..^"Async".Length];
            yield return method + "Command";
        }
    }

    private static IEnumerable<string> ProductSources()
    {
        var root = Path.Combine(TestPaths.RepoRoot(), "DotCharter.UI");
        foreach (var file in UiSourceTree.EnumerateFiles(root, "*.*", SearchOption.AllDirectories))
        {
            if (!file.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) &&
                !file.EndsWith(".axaml", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var relative = Path.GetRelativePath(root, file);
            if (relative.StartsWith("bin", StringComparison.OrdinalIgnoreCase) ||
                relative.StartsWith("obj", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            yield return file;
        }
    }

    /// <summary>
    ///     The screen contracts a file's types declare they implement.
    ///     <para>
    ///         A migrated tab's view binds <c>x:DataType="contracts:IFooScreen"</c>
    ///         and never names the view model at all, so without this every
    ///         command on a half-migrated tab reads as ambiguous the moment its
    ///         markup is repointed — which is exactly what happened to the Audio
    ///         tab. Naming a contract the declaring type implements is as
    ///         specific as naming the type: nothing else implements it.
    ///     </para>
    /// </summary>
    private static IEnumerable<string> ContractsImplementedIn(string text) =>
        Regex.Matches(text, @"class\s+\w+\s*:\s*([^
{]+)")
            .SelectMany(m => m.Groups[1].Value.Split(','))
            .Select(t => t.Trim())
            .Where(t => t.Length > 2 && t[0] == 'I' && char.IsUpper(t[1]) && t.EndsWith("Screen", StringComparison.Ordinal))
            .Distinct(StringComparer.Ordinal);
}
