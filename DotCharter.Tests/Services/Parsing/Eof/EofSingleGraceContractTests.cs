    [Fact]
    public void An_authored_marked_sixteenth_slide_is_not_a_synthesized_ornament()
    {
        var beats = Beats([0, 600, 1200, 1800, 2400]);
        var first = new EofRawProGuitarNote
        {
            Name = "[DotCharter grace]", NoteBitmask = 1, PositionMs = 1200, LengthMs = 150,
            Flags = EofConstants.PgFlagLinkNext | EofConstants.PgFlagRsNotation | EofConstants.PgFlagSlideUp,
            SlideEndFret = 7
        };
        first.Frets[0] = 5;
        var target = new EofRawProGuitarNote { NoteBitmask = 1, PositionMs = 1350, LengthMs = 150 };
        target.Frets[0] = 7;

        var notes = Assert.Single(Parse([first, target], beats).Levels).Notes;

        Assert.Equal(2, notes.Count);
        Assert.Equal(new[] { 5, 7 }, notes.Select(n => n.Fret));
        Assert.Equal(new[] { 1200.0, 1350.0 }, notes.Select(n => n.Position.GetPositionMs(beats)));
        Assert.Equal(7, notes[0].SlideTo);
        Assert.All(notes, n => Assert.Null(n.GraceFret));
    }

    [Fact]
    public void The_exporter_marker_set_equals_the_importer_fold_set_for_single_ornaments()
    {
        var cases = new (double[] Times, FractionalPosition Position, uint Length, int Grace, int Fret, int String, int Capo, bool GhostTarget)[]
        {
            ([0, 600, 1200, 1800, 2400, 3000], new FractionalPosition(2), 75, 5, 7, 0, 0, false),
            ([0, 600, 1200, 1800, 2400, 3000], new FractionalPosition(2), 75, 9, 5, 5, 2, false),
            ([0, 1500, 3000, 4500, 6000, 7500], new FractionalPosition(2), 188, 5, 7, 2, 0, false),
            ([0, 2000, 4000, 6000, 8000, 10000], new FractionalPosition(2), 200, 5, 7, 0, 0, false),
            ([0, 1, 2, 3, 4, 5], new FractionalPosition(2), 1, 5, 7, 0, 0, false),
            ([0, 1536, 2688, 3840, 4992, 6144], new FractionalPosition(1, new Fraction(9, 256)), 179, 5, 7, 0, 0, false),
            ([0, 1600, 1700, 1800, 1900, 2000], new FractionalPosition(1, new Fraction(3, 2000)), 200, 5, 7, 0, 0, false)
        };
        foreach (var row in cases)
        {
            var beats = Beats(row.Times);
            var arrangement = new Arrangement { Name = "Lead", Capo = row.Capo, Levels = { new ChartLevel() } };
            arrangement.Levels[0].Notes.Add(new GuitarNote
            {
                Position = row.Position, Sustain = new FractionalPosition(2), StringIndex = row.String,
                Fret = row.Fret, GraceFret = row.Grace, Accent = true, Vibrato = true, Ignore = true
            });
            if (row.GhostTarget)
            {
                arrangement.ChordTemplates.Add(new ChordTemplate
                {
                    Id = 0, Frets = { [0] = row.Fret, [1] = 9 }, GhostMask = ChordTemplate.GhostBit(1)
                });
                arrangement.Levels[0].HandShapes.Add(new HandShape
                {
                    Position = row.Position, EndPosition = row.Position + new FractionalPosition(1), TemplateId = 0
                });
            }
            var emitted = EofNoteBuilder.Build(arrangement, beats).Select(n => WireCopy(n.Raw)).ToList();
            Assert.Equal(2, emitted.Count);
            Assert.Equal("[DotCharter grace]", emitted[0].Name);
            Assert.Equal(row.Length, emitted[0].LengthMs);
            AssertFold("emitted", emitted, beats, row.Capo, canEmit: true);
            var folded = Assert.Single(Assert.Single(Parse(emitted, beats, row.Capo).Levels).Notes);
            Assert.Equal(row.Grace, folded.GraceFret);
            Assert.Equal((row.Fret, true, true, true), (folded.Fret, folded.Accent, folded.Vibrato, folded.Ignore));

            // Each bit change produces an ornament record the writer cannot emit.
            // The extended marker bit is generated by the wire writer, tested separately.
            for (var bit = 0; bit < 31; bit++)
            {
                var changed = Copy(emitted);
                changed[0].Flags ^= 1u << bit;
                AssertFold("flag bit " + bit, changed, beats, row.Capo, canEmit: false);
            }
            foreach (var mutation in OutsideTheEmissionSet(row.String))
            {
                var changed = Copy(emitted);
                mutation.Change(changed);
                AssertFold(mutation.Name, changed, beats, row.Capo, canEmit: false);
            }
            AssertFold("assigned ornament finger", emitted, beats, row.Capo, canEmit: false, finger: 1);
            var intervening = Copy(emitted);
            var extra = new EofRawProGuitarNote
            {
                NoteBitmask = emitted[0].NoteBitmask, PositionMs = emitted[0].PositionMs + 1, LengthMs = 1
            };
            extra.Frets[row.String] = 11;
            intervening.Insert(1, extra);
            AssertFold("earlier same-string target", intervening, beats, row.Capo, canEmit: false);
            extra.NoteBitmask = (byte)(1 << ((row.String + 1) % 8));
            extra.Frets[(row.String + 1) % 8] = 11;
            AssertFold("unrelated string between pair", intervening, beats, row.Capo, canEmit: true);
        }
    }

    [Fact]
    public void An_edited_ornament_keeps_its_own_tech_slide_and_both_attacks()
    {
        var notes = CanonicalPair();
        var data = new AttachmentData();
        AddAttachment("slide tech", data, notes, 2450, 0, 1);
        var beats = AttachmentBeats();

        var imported = Assert.Single(Parse(notes, beats, attachments: data).Levels).Notes;

        Assert.Equal(2, imported.Count);
        Assert.Equal(new[] { 5, 7 }, imported.Select(n => n.Fret));
        Assert.Equal(new[] { 2400.0, 2550.0 }, imported.Select(n => n.Position.GetPositionMs(beats)));
        Assert.Equal(9, imported[0].SlideTo);
        Assert.Null(imported[1].SlideTo);
        Assert.All(imported, n => Assert.Null(n.GraceFret));
    }

    [Fact]
    public void Attachment_kinds_follow_export_capability_and_other_kinds_veto_when_applicable()
    {
        var families = new[]
        {
            "slide tech", "bend tech", "plain tech", "trill", "tremolo", "arpeggio",
            "handshape", "flagged handshape", "anchor", "tone", "ornament finger", "target finger",
            "target ghost grip", "pure ghost grip"
        };
        foreach (var family in families)
        {
            AssertAttachmentFold(family + " absent", CanonicalPair(), new AttachmentData(), shouldFold: true);
            foreach (var at in new uint[] { 2400, 2450, 2550 })
            {
                var notes = CanonicalPair();
                var data = new AttachmentData();
                AddAttachment(family, data, notes, at, 0, 1);
                var veto = family is "slide tech" or "plain tech" or "ornament finger" ||
                           family == "trill" && at is 2400 or 2550;
                AssertAttachmentFold(family + " present at " + at, notes, data, shouldFold: !veto);
            }
            if (family.Contains("finger", StringComparison.Ordinal) || family == "target ghost grip") continue;
            foreach (var at in new uint[] { 2398, 2551 })
            {
                var notes = CanonicalPair();
                var data = new AttachmentData();
                AddAttachment(family, data, notes, at, 0, 1);
                AssertAttachmentFold(family + " outside at " + at, notes, data, shouldFold: true);
            }
            var otherNotes = CanonicalPair();
            var other = new AttachmentData();
            AddAttachment(family, other, otherNotes, 2450, 1, 1);
            AssertAttachmentFold(family + " other difficulty", otherNotes, other, shouldFold: true);
            if (!family.Contains("tech", StringComparison.Ordinal) && family != "pure ghost grip") continue;
            otherNotes = CanonicalPair();
            other = new AttachmentData();
            AddAttachment(family, other, otherNotes, 2450, 0, 2);
            AssertAttachmentFold(family + " other string", otherNotes, other, shouldFold: true);
        }
        var overlap = new AttachmentData();
        var pair = CanonicalPair();
        AddAttachment("slide tech", overlap, pair, 2350, 0, 1);
        overlap.TechNotes[0].LengthMs = 100;
        AssertAttachmentFold("tech starts before but overlaps without applying", pair, overlap, shouldFold: true);
        AssertForeignFingerDoesNotBlock(1, 0);
        AssertForeignFingerDoesNotBlock(0, 1);
    }

    [Fact]
    public void Text_events_and_mover_phrases_are_attachment_row_families_in_full_files()
    {
        foreach (var kind in new[] { "phrase", "section", "event", "untyped", "solo phrase", "combined", "moveR" })
        {
            Assert.Equal(2, ImportTextFixture(kind, present: false).Levels.Sum(l => l.Notes.Count));
            foreach (var atAttack in new[] { false, true })
            {
                var back = ImportTextFixture(kind, present: true, atAttack: atAttack);
                Assert.Equal(2, back.Levels.Sum(l => l.Notes.Count));
                Assert.Equal(5, back.Levels[0].Notes[0].GraceFret);
                var global = ImportTextFixture(kind, present: true, global: true, atAttack: atAttack);
                Assert.Equal(2, global.Levels.Sum(l => l.Notes.Count));
            }
            Assert.Equal(2, ImportTextFixture(kind, present: true, otherTrack: true).Levels.Sum(l => l.Notes.Count));
        }
        var moved = ImportTextFixture("moveR", present: true);
        Assert.Equal(4800, Assert.Single(moved.EventPoints).Position.GetPositionMs(AttachmentBeats()));
    }

    private sealed class AttachmentData
    {
        public List<EofRawProGuitarNote> TechNotes { get; } = [];
        public List<(ushort Type, byte Difficulty, uint Start, uint End, uint Flags, string Name)> Sections { get; } = [];
        public Dictionary<(int Note, int String), byte> Fingers { get; } = [];
    }

    private static List<BeatMarker> AttachmentBeats() => Beats([0, 1200, 2400, 3600, 4800, 6000]);

    private static List<EofRawProGuitarNote> CanonicalPair()
    {
        var ornament = new EofRawProGuitarNote
        {
            Name = "[DotCharter grace]", NoteBitmask = 1, PositionMs = 2400, LengthMs = 150,
            Flags = EofConstants.PgFlagLinkNext | EofConstants.PgFlagRsNotation | EofConstants.PgFlagSlideUp,
            SlideEndFret = 7
        };
        ornament.Frets[0] = 5;
        var target = new EofRawProGuitarNote { NoteBitmask = 1, PositionMs = 2550, LengthMs = 150 };
        target.Frets[0] = 7;
        return [ornament, target];
    }

    private static void AddAttachment(string family, AttachmentData data, List<EofRawProGuitarNote> notes,
        uint at, byte difficulty, byte mask)
    {
        if (family.Contains("tech", StringComparison.Ordinal))
        {
            var tech = new EofRawProGuitarNote
            {
                PositionMs = at, LengthMs = 1, Difficulty = difficulty, NoteBitmask = mask,
                Flags = family == "slide tech" ? EofConstants.PgFlagRsNotation | EofConstants.PgFlagSlideUp :
                    family == "bend tech" ? EofConstants.PgFlagRsNotation | EofConstants.PgFlagBend : 0,
                SlideEndFret = 9, BendStrength = 2
            };
            data.TechNotes.Add(tech);
            return;
        }
        if (family.Contains("finger", StringComparison.Ordinal))
        {
            data.Fingers[(family == "ornament finger" ? 0 : 1, 0)] = 1;
            return;
        }
        if (family == "target ghost grip")
        {
            notes[1].NoteBitmask = 3;
            notes[1].GhostBitmask = 2;
            notes[1].Frets[1] = 9;
            return;
        }
        if (family == "pure ghost grip")
        {
            var ghost = new EofRawProGuitarNote { PositionMs = at, Difficulty = difficulty, NoteBitmask = mask, GhostBitmask = mask };
            notes.Add(ghost);
            notes.Sort((a, b) => a.PositionMs.CompareTo(b.PositionMs));
            return;
        }
        var type = family switch
        {
            "trill" => EofConstants.SectionTrill,
            "tremolo" => EofConstants.SectionTremolo,
            "anchor" => EofConstants.SectionFretHandPos,
            "tone" => EofConstants.SectionRsToneChange,
            "handshape" => EofConstants.SectionHandshape,
            _ => EofConstants.SectionArpeggio
        };
        var end = family == "anchor" ? 5u : family == "tone" ? 0u : at + 1;
        data.Sections.Add(((ushort)type, difficulty, at, end, family == "flagged handshape" ? 2u : 0u,
            family == "tone" ? "tone" : ""));
    }

    private static void AssertAttachmentFold(string label, List<EofRawProGuitarNote> notes, AttachmentData data, bool shouldFold)
    {
        var back = Parse(notes, AttachmentBeats(), attachments: data);
        var folded = back.Levels.SelectMany(l => l.Notes).Count(n => n.GraceFret != null);
        Assert.True(folded == (shouldFold ? 1 : 0), $"{label}: folds={folded}, expected={shouldFold}");
        Assert.Equal(notes.Count(n => (n.NoteBitmask & ~n.GhostBitmask) != 0) - (shouldFold ? 1 : 0),
            back.Levels.Sum(l => l.Notes.Count + l.Chords.Count));
    }

    private static void AssertForeignFingerDoesNotBlock(byte difficulty, int s)
    {
        var notes = CanonicalPair();
        var foreign = new EofRawProGuitarNote { PositionMs = 2450, Difficulty = difficulty, NoteBitmask = (byte)(1 << s) };
        foreign.Frets[s] = 11;
        notes.Add(foreign);
        var data = new AttachmentData();
        data.Fingers[(2, s)] = 1;
        AssertAttachmentFold("foreign finger", notes, data, shouldFold: true);
    }

    private static Arrangement ImportTextFixture(string kind, bool present, bool global = false,
        bool otherTrack = false, bool atAttack = false)
    {
        var project = new ChartProject();
        foreach (var beat in AttachmentBeats()) project.Beats.Add(beat);
        var lead = new Arrangement { Name = "Lead", Levels = { new ChartLevel() } };
        lead.Levels[0].Notes.Add(new GuitarNote
        {
            Position = new FractionalPosition(2), Sustain = new FractionalPosition(2), StringIndex = 0, Fret = 7, GraceFret = 5
        });
        lead.Levels[0].Notes.Add(new GuitarNote { Position = new FractionalPosition(4), StringIndex = 0, Fret = 9 });
        project.Arrangements.Add(lead);
        var owner = lead;
        if (otherTrack)
        {
            owner = new Arrangement { Name = "Rhythm", ArrangementType = ArrangementType.Rhythm, Levels = { new ChartLevel() } };
            owner.Levels[0].Notes.Add(new GuitarNote { Position = new FractionalPosition(2), StringIndex = 0, Fret = 10 });
            project.Arrangements.Add(owner);
        }
        if (present)
        {
            var position = kind == "moveR" ? new FractionalPosition(0) :
                new FractionalPosition(2, atAttack ? new Fraction(1, 8) : new Fraction(1, 24));
            owner.EventPoints.Add(new EventPoint
            {
                Position = position, Phrase = kind is "phrase" or "untyped" or "solo phrase" or "combined" ? "phrase" : kind == "moveR" ? "moveR2" : "",
                Section = kind == "combined" ? "phrase" : kind == "section" ? "section" : "", Events = kind == "event" ? "event" : ""
            });
        }
        if (kind == "solo phrase") owner.PhraseInfos["phrase"] = new PhraseInfo(0, true);
        var bytes = EofExporter.Export(project).Bytes;
        if (present && (global || kind == "untyped")) PatchTextClassification(bytes, global, kind == "untyped");
        var path = Path.Combine(Path.GetTempPath(), "dc-eof-attachments-" + Guid.NewGuid().ToString("N") + ".eof");
        File.WriteAllBytes(path, bytes);
        try
        {
            return Assert.Single(new EofImporter().ImportTracksWithMetadata(path, [9]).Arrangements);
        }
        finally
        {
            File.Delete(path);
        }
    }

    private static void PatchTextClassification(byte[] bytes, bool global, bool untyped)
    {
        var reader = new EofPackReader(bytes);
        var session = new EofParseSession(reader);
        session.ReadHeaderAndProperties();
        session.ReadIniBlocks();
        session.ReadOggProfiles();
        session.ReadBeats();
        var count = reader.ReadU32();
        Assert.True(count > 0);
        for (var i = 0; i < count; i++)
        {
            reader.ReadString();
            reader.ReadU32();
            var trackOffset = reader.Position;
            reader.ReadU16();
            var flagOffset = reader.Position;
            var flags = reader.ReadU16();
            if (global) BinaryPrimitives.WriteUInt16LittleEndian(bytes.AsSpan(trackOffset, 2), 0);
            if (untyped) BinaryPrimitives.WriteUInt16LittleEndian(bytes.AsSpan(flagOffset, 2), (ushort)(flags & 16));
        }
    }

    private static List<(string Name, Action<List<EofRawProGuitarNote>> Change)> OutsideTheEmissionSet(int s) =>
    [
        ("no marker", n => n[0].Name = ""),
        ("different marker", n => n[0].Name = "[DotCharter Grace]"),
        ("zero duration", n => n[0].LengthMs = 0),
        ("above duration cap", n => n[0].LengthMs = 201),
        ("noncanonical duration", n =>
        {
            n[0].LengthMs++;
            n[1].PositionMs++;
        }),
        ("reserved difficulty", n =>
        {
            n[0].Difficulty = 255;
            n[1].Difficulty = 255;
        }),
        ("different difficulty", n => n[1].Difficulty++),
        ("ghost origin", n => n[0].GhostBitmask = n[0].NoteBitmask),
        ("ghost carrier", n =>
        {
            n[0].NoteBitmask |= (byte)(1 << ((s + 1) % 8));
            n[0].GhostBitmask = (byte)(1 << ((s + 1) % 8));
        }),
        ("legacy mask", n => n[0].LegacyMask = 1),
        ("extended technique", n => n[0].ExtendedFlags = 1),
        ("open origin", n => n[0].Frets[s] = 0),
        ("muted origin", n => n[0].Frets[s] |= 0x80),
        ("no interval", n => n[0].Frets[s] = n[1].Frets[s]),
        ("wrong slide target", n => n[0].SlideEndFret++),
        ("open target", n => n[1].Frets[s] = 0),
        ("muted target", n => n[1].Frets[s] |= 0x80),
        ("named target", n => n[1].Name = "Authored target"),
        ("target gap", n => n[1].PositionMs++),
        ("target overlap", n => n[1].PositionMs--)
    ];

    private static void AssertFold(string label, List<EofRawProGuitarNote> notes, List<BeatMarker> beats,
        int capo, bool canEmit, byte finger = 0)
    {
        var imported = Parse(notes, beats, capo, finger);
        var folded = imported.Levels.SelectMany(l => l.Notes).Count(n => n.GraceFret != null);
        Assert.True(folded == (canEmit ? 1 : 0), $"{label}: exporter identity={canEmit}, imported folds={folded}, onset={notes[0].PositionMs}, length={notes[0].LengthMs}");
        var sounds = imported.Levels.Sum(l => l.Notes.Count + l.Chords.Count);
        Assert.Equal(notes.Count(n => (n.NoteBitmask & ~n.GhostBitmask) != 0) - (canEmit ? 1 : 0), sounds);
    }

    private static List<BeatMarker> Beats(double[] times) => times.Select(t => new BeatMarker { Time = t }).ToList();

    private static EofRawProGuitarNote WireCopy(EofRawProGuitarNote note)
    {
        var writer = new EofPackWriter();
        EofProGuitarNoteWriter.Write(writer, note);
        return EofProGuitarNoteReader.Read(new EofPackReader(writer.ToArray()));
    }

    private static List<EofRawProGuitarNote> Copy(List<EofRawProGuitarNote> notes) => notes.Select(WireCopy).ToList();

    private static Arrangement Parse(List<EofRawProGuitarNote> notes, List<BeatMarker> beats, int capo = 0,
        byte finger = 0, AttachmentData? attachments = null)
    {
        attachments ??= new AttachmentData();
        var writer = new EofPackWriter();
        writer.WriteU8(24);
        writer.WriteU8(8);
        for (var s = 0; s < 8; s++) writer.WriteU8(0);
        writer.WriteU32((uint)notes.Count);
        foreach (var note in notes) EofProGuitarNoteWriter.Write(writer, note);
        WriteSections(writer, attachments);
        var withFingers = finger != 0 || attachments.Fingers.Count != 0;
        writer.WriteU32((uint)((capo != 0 ? 1 : 0) + (withFingers ? 1 : 0) + (attachments.TechNotes.Count != 0 ? 1 : 0)));
        if (capo != 0)
        {
            writer.WriteU32(5);
            writer.WriteU32(EofConstants.PgCustomCapoPosition);
            writer.WriteU8((byte)capo);
        }
        if (withFingers)
        {
            writer.WriteU32(4 + (uint)notes.Sum(n => BitOperations.PopCount(n.NoteBitmask)));
            writer.WriteU32(EofConstants.PgCustomFingerArray);
            for (var i = 0; i < notes.Count; i++)
            {
                for (var s = 0; s < 8; s++)
                {
                    if ((notes[i].NoteBitmask & (1 << s)) == 0) continue;
                    var value = attachments.Fingers.GetValueOrDefault((i, s), i == 0 ? finger : (byte)0);
                    writer.WriteU8(value);
                }
            }
        }
        if (attachments.TechNotes.Count != 0)
        {
            var payload = new EofPackWriter();
            payload.WriteU32((uint)attachments.TechNotes.Count);
            foreach (var tech in attachments.TechNotes) EofProGuitarNoteWriter.Write(payload, tech);
            writer.WriteU32((uint)(4 + payload.Length));
            writer.WriteU32(EofConstants.PgCustomTechNotes);
            writer.WriteBytes(payload.ToArray());
        }
        return EofProGuitarTrackParser.Parse(new EofPackReader(writer.ToArray()), new EofTrackInfo { Id = 9, Name = "Lead" }, beats);
    }

    private static void WriteSections(EofPackWriter writer, AttachmentData attachments)
    {
        var groups = attachments.Sections.GroupBy(s => s.Type).ToList();
        writer.WriteU16((ushort)groups.Count);
        foreach (var group in groups)
        {
            writer.WriteU16(group.Key);
            writer.WriteU32((uint)group.Count());
            foreach (var section in group)
            {
                writer.WriteString(section.Name);
                writer.WriteU8(section.Difficulty);
                writer.WriteU32(section.Start);
                writer.WriteU32(section.End);
                writer.WriteU32(section.Flags);
            }
        }
    }
