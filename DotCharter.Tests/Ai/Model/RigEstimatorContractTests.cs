using DotCharter.Services.Ai.Match;
using DotCharter.Services.Ai.Match.Model;
using DotCharter.Tone.Infrastructure.Storage;

namespace DotCharter.Tests.Ai.Model;

/// <summary>
///     The guard on the claim that the v2 model export is ADDITIVE: a reader
///     that knows only v1's four outputs must decode a v2 model, unchanged.
///     <para>
///         This is the claim that let <see cref="RigLabelVocabulary.SchemaVersion" />
///         stay at 1 while the trainer grew a whole new head. If it is false,
///         the failure is at the worst possible moment and in the worst
///         possible shape: the app loads, <c>IsAvailable</c> is true, and the
///         first estimate throws inside the ONNX session — where the load
///         failure LATCHES and every caller silently degrades to search-only
///         for the rest of the process.
///     </para>
///     <para>
///         The v2 export publishes <c>chain_tokens</c> and <c>chain_knobs</c>
///         beside the four. Until 2026-09-13 <c>EstimateAsync</c> materialised
///         EVERY result into <c>float[]</c>, so it threw on any extra output
///         that was not float — which is exactly what the chain tokens were
///         (int64) on the first cut. Both halves were fixed: the reader takes
///         only the four it needs, by name, and the exporter publishes the
///         tokens as float. This test pins the reader half; it fails if a later
///         change goes back to mapping everything.
///     </para>
///     <para>
///         The fixture is a ~23 KB ONNX with the v2 output SIGNATURE and
///         constant, hand-chosen answers — the contract without the model. A
///         real v2 export is tens of MB and is not bundled, so a test against
///         one could only ever skip. It is generated by
///         <c>tools/rig-model/tests/make_contract_fixture.py</c>; regenerate it
///         when the signature changes.
///     </para>
/// </summary>
public sealed class RigEstimatorContractTests
{
    private const string FixtureName = "rig-estimator-v2-contract.onnx";

    /// <summary>The two modules the fixture's chain names, in order. Mirrors
    /// <c>CHAIN</c> in the generator, which takes catalogue indices 0 and 1.</summary>
    private static (string Id, float Knob)[] ExpectedChain =>
    [
        (RigLabelVocabulary.Modules[0].TypeId, 0.25f),
        (RigLabelVocabulary.Modules[1].TypeId, 0.25f),
    ];

    [Fact]
    public async Task AV2ShapedModel_IsDecodedByTheV1Reader_WithNoSchemaBump()
    {
        var fixture = FixturePath();
        Assert.True(File.Exists(fixture),
            $"{fixture} is missing. It is a committed build product of "
            + "tools/rig-model/tests/make_contract_fixture.py — regenerate it rather than "
            + "deleting this test.");

        var dir = Path.Combine(Path.GetTempPath(), "dc-rig-contract-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        try
        {
            File.Copy(fixture, Path.Combine(dir, "model.onnx"));
            // The sidecar is written from the LIVE vocabulary rather than
            // committed beside the model: that way a catalogue change moves the
            // fixture's label space with it, instead of leaving a stale copy
            // that passes while meaning something else.
            File.WriteAllText(Path.Combine(dir, "model.sidecar.json"), RigLabelVocabulary.ToJson());

            using var estimator = new RigEstimatorOnnx(dir);
            Assert.True(estimator.IsAvailable,
                "a v2-shaped model did not even LOAD through the v1 reader");

            var samples = RigLabelVocabulary.SampleRate
                          * (int)Math.Round(RigLabelVocabulary.ClipSeconds);
            var audio = new float[samples];
            for (var i = 0; i < samples; i++)
                audio[i] = 0.2f * MathF.Sin(2f * MathF.PI * 110f * i / RigLabelVocabulary.SampleRate);

            var estimate = await estimator.EstimateAsync(
                new MonoAudio(audio, RigLabelVocabulary.SampleRate), TestContext.Current.CancellationToken);

            // The chain the fixture published, read back through the v1 path:
            // slot_probs -> argmax -> module id, knob_values -> Denormalise.
            Assert.Equal(ExpectedChain.Select(c => c.Id),
                         estimate.Rig.Modules.Select(m => m.ModuleTypeId));
            Assert.InRange(estimate.Confidence, 0.74f, 0.76f);

            foreach (var (id, unit) in ExpectedChain)
            {
                var entry = RigLabelVocabulary.Modules.Single(m => m.TypeId == id);
                var module = estimate.Rig.Modules.Single(m => m.ModuleTypeId == id);
                foreach (var spec in entry.Params)
                {
                    var expected = RigLabelVocabulary.Denormalise(spec, unit);
                    Assert.True(Math.Abs(module.Params[spec.Id] - expected) < 1e-3f,
                        $"{id}.{spec.Id}: read {module.Params[spec.Id]}, expected {expected} "
                        + $"(the knob vector is being read at the wrong offset)");
                }
            }
        }
        finally
        {
            BestEffortDelete.Directory(dir);
        }
    }

    private static string FixturePath()
    {
        // The fixture is copied beside the test assembly by the csproj; the
        // source-tree walk is the fallback for a runner that did not.
        var beside = Path.Combine(AppContext.BaseDirectory, "Ai", "Model", "Assets", FixtureName);
        if (File.Exists(beside)) return beside;

        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null)
        {
            var candidate = Path.Combine(dir.FullName, "DotCharter.Tests", "Ai", "Model",
                                         "Assets", FixtureName);
            if (File.Exists(candidate)) return candidate;
            dir = dir.Parent;
        }

        return beside;
    }
}
