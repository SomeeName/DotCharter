using System.Globalization;
using System.Text;
using DotCharter.Analysis.AudioToChart;
using DotCharter.Services.Import.Audio;
using DotCharter.Tests.Ai.AudioEval;
using static DotCharter.Tests.Analysis.AutoChartCorpus;

namespace DotCharter.Tests.Analysis;

/// <summary>
///     The stem half of the auto-chart score (#391): the same draft from the
///     instrument's separated stem against the draft from the MIX, on the same audio.
///     <para>
///     <b>Why excerpts.</b> No whole corpus song has cached stems, and stems are never
///     separated for an eval. The stems that DO exist are the tone-match audio eval's
///     (<see cref="AudioEvalCorpus" />): one ≤30 s excerpt per elected tone, separated
///     once, whose lossless raw output the stem cache keeps. The excerpt is
///     regenerated byte for byte from the song's mix (<see cref="AudioEvalCorpus.EnsureExcerpt" />,
///     into a directory OUTSIDE the repo), so its content key finds those stems through
///     the product's own <see cref="ChartFromAudioStemLocator" /> — read-only, the app's
///     real cache, nothing written there.
///     </para>
///     <para>
///     Each arrangement of the song is scored over the excerpt's span, minus
///     <see cref="EdgeSeconds" /> at each end (the detector's reference window has no
///     past at the start), with the chart's own beat grid; the mix draft and the stem
///     draft see exactly the same window. Like the main harness it asserts nothing about
///     accuracy. Skipped unless <c>DOTCHARTER_AUTOCHART_CORPUS=1</c> and
///     <c>DOTCHARTER_AUTOCHART_EXCERPTS</c> names the excerpt directory.
///     </para>
/// </summary>
public sealed class AutoChartStemSubsetProbeTests(ITestOutputHelper output)
{
    private const string EnvVar = "DOTCHARTER_AUTOCHART_CORPUS";
    private const string ExcerptsEnvVar = "DOTCHARTER_AUTOCHART_EXCERPTS";
    private const string OutEnvVar = "DOTCHARTER_AUTOCHART_CORPUS_OUT";

    /// <summary>Trimmed off both ends of every excerpt before scoring.</summary>
    public const double EdgeSeconds = 0.5;

    private sealed record SpanRow(string Song, string Arrangement, string Kind, string Stem, double From, double To,
        AutoChartScore Mix, AutoChartScore Stemmed);

    [Fact]
    public void ScoreTheCachedStemsAgainstTheMixOnTheSameExcerpts()
    {
        Assert.SkipWhen(Environment.GetEnvironmentVariable(EnvVar) != "1",
            $"Stem subset score: set {EnvVar}=1 and {ExcerptsEnvVar}=<dir outside the repo>.");
        var excerpts = Environment.GetEnvironmentVariable(ExcerptsEnvVar);
        Assert.SkipWhen(string.IsNullOrWhiteSpace(excerpts), $"Set {ExcerptsEnvVar}=<dir outside the repo>.");
        var root = AutoChartCorpusProbeTests.FindTestDataRoot();
        Assert.SkipWhen(root is null, "No TestData/ (it is git-ignored).");
        var eof = Path.GetFullPath(Path.Combine(root!, "EOF")) + Path.DirectorySeparatorChar;
        var repo = Path.GetFullPath(Path.GetDirectoryName(root!)!) + Path.DirectorySeparatorChar;
        excerpts = Path.GetFullPath(excerpts!);
        Assert.False(excerpts.StartsWith(repo, StringComparison.OrdinalIgnoreCase),
            $"{ExcerptsEnvVar} must be OUTSIDE the repo; got {excerpts}.");

        var load = AudioEvalCorpus.LoadDetailed(root!, limit: 1000);
        var spans = load.Rows
            .Where(r => Path.GetFullPath(r.SongAudioPath).StartsWith(eof, StringComparison.OrdinalIgnoreCase))
            .GroupBy(r => (r.SongAudioPath, r.From, r.To))
            .Select(g => g.First())
            .OrderBy(r => r.SongAudioPath, StringComparer.Ordinal).ThenBy(r => r.From)
            .ToList();

        var locator = new ChartFromAudioStemLocator();
        var rows = new List<SpanRow>();
        var notes = new List<string>();
        foreach (var span in spans)
        {
            var songDir = Path.GetDirectoryName(span.SongAudioPath)!;
            var song = Path.GetFileName(songDir);
            var excerpt = AudioEvalCorpus.EnsureExcerpt(span, excerpts);
            var from = span.From.TotalSeconds;
            var (mixSamples, mixRate) = WavMonoReader.Read(excerpt);
            var to = from + mixSamples.Length / (double)mixRate;
            var mixEvents = Shift(new AudioToChartAnalyzer().DetectEvents(mixSamples, mixRate), from);
            var mixCqt = CqtPitchEvidence.FromWholeClip(mixSamples, mixRate, from);
            var stemEvents = new Dictionary<string, (List<GuitarAudioEvent> Events, CqtPitchEvidence Cqt)>(StringComparer.Ordinal);

            foreach (var (name, project, arrangement) in AutoChartCorpusProbeTests.LoadCharts(songDir, notes))
            {
                var stem = locator.TryLocate(excerpt, arrangement.ArrangementType);
                if (stem == null)
                {
                    notes.Add($"{song} {from:0}–{to:0} s / {name}: no lossless {arrangement.ArrangementType} stem cached");
                    continue;
                }

                if (!stemEvents.TryGetValue(stem.StemName, out var stemmed))
                {
                    var (stemSamples, stemRate) = WavMonoReader.Read(stem.ReadWavBytes());
                    stemmed = (Shift(new AudioToChartAnalyzer().DetectEvents(stemSamples, stemRate), from),
                        CqtPitchEvidence.FromWholeClip(stemSamples, stemRate, from));
                    stemEvents[stem.StemName] = stemmed;
                }

                var lo = from + EdgeSeconds;
                var hi = to - EdgeSeconds;
                var truth = Window(GroundTruth(arrangement, project.Beats), lo, hi);
                if (truth.Count == 0) continue;
                var options = ChartFromAudioAnalyzer.OptionsFor(arrangement, ChartFromAudioAnalyzer.DefaultSensitivity);
                AutoChartScore Score(List<GuitarAudioEvent> evs, CqtPitchEvidence cqt) => AutoChartScorer.Score(truth,
                    Window(DraftSounds(AudioToChartAnalyzer.DraftFromEvents(evs, project.Beats, options, cqt), project.Beats,
                        snapped: true), lo, hi), ToleranceSeconds);
                rows.Add(new SpanRow(song, name, arrangement.ArrangementType.ToString(), stem.StemName, from, to,
                    Score(mixEvents, mixCqt), Score(stemmed.Events, stemmed.Cqt)));
            }
        }

        Assert.SkipWhen(rows.Count == 0,
            $"No excerpt of {spans.Count} has a lossless stem in the stem cache ({notes.Count} notes).");

        var report = Report(rows, spans.Count, notes);
        output.WriteLine(report);
        var outDir = Environment.GetEnvironmentVariable(OutEnvVar);
        if (!string.IsNullOrWhiteSpace(outDir))
        {
            outDir = Path.GetFullPath(outDir);
            Assert.False(outDir.StartsWith(repo, StringComparison.OrdinalIgnoreCase), $"{OutEnvVar} must be OUTSIDE the repo.");
            Directory.CreateDirectory(outDir);
            File.WriteAllText(Path.Combine(outDir, "stems-report.md"), report);
        }
    }

    /// <summary>Events from an excerpt that starts <paramref name="seconds" /> into the song, on the song's clock.</summary>
    internal static List<GuitarAudioEvent> Shift(IEnumerable<GuitarAudioEvent> events, double seconds) =>
        events.Select(e => e with { TimeSeconds = e.TimeSeconds + seconds }).ToList();

    internal static List<ScoredSound> Window(IEnumerable<ScoredSound> sounds, double lo, double hi) =>
        sounds.Where(s => s.TimeSeconds >= lo && s.TimeSeconds <= hi).ToList();

    private static string Report(List<SpanRow> rows, int spans, List<string> notes)
    {
        var sb = new StringBuilder();
        var songs = rows.Select(r => r.Song).Distinct(StringComparer.Ordinal).Count();
        var excerpts = rows.Select(r => (r.Song, r.From)).Distinct().Count();
        var seconds = rows.Select(r => (r.Song, r.From, r.To)).Distinct().Sum(r => r.To - r.From - 2 * EdgeSeconds);
        sb.AppendLine("# Auto-chart stem subset: the instrument's stem vs the mix, same excerpts");
        sb.AppendLine();
        sb.AppendLine(string.Create(CultureInfo.InvariantCulture,
            $"{excerpts} excerpts of {spans} (with a lossless stem cached) from {songs} songs, {seconds / 60:0.0} min of audio, " +
            $"{rows.Count} arrangement spans. ±{ToleranceSeconds * 1000:0} ms, default sensitivity, snapped draft."));
        sb.AppendLine();
        sb.AppendLine("| kind | spans | source | onset P | onset R | onset F1 | pitch acc. | note P | note R | note F1 |");
        sb.AppendLine("|---|---:|---|---:|---:|---:|---:|---:|---:|---:|");
        var groups = rows.GroupBy(r => r.Kind).OrderBy(g => g.Key, StringComparer.Ordinal)
            .Select(g => (Label: g.Key, Set: g.ToList()))
            .Prepend((Label: "**ALL**", Set: rows));
        foreach (var (label, set) in groups)
        {
            sb.AppendLine(Line(label, set.Count, "mix", Sum(set.Select(r => r.Mix))));
            sb.AppendLine(Line(label, set.Count, "stem", Sum(set.Select(r => r.Stemmed))));
        }

        sb.AppendLine();
        sb.AppendLine("| song | arrangement | span s | stem | mix onset F1 | stem onset F1 | mix note F1 | stem note F1 |");
        sb.AppendLine("|---|---|---|---|---:|---:|---:|---:|");
        foreach (var r in rows)
        {
            sb.AppendLine(string.Create(CultureInfo.InvariantCulture,
                $"| {r.Song} | {r.Arrangement} | {r.From:0}–{r.To:0} | {r.Stem} | {Pct(r.Mix.OnsetF1)} | {Pct(r.Stemmed.OnsetF1)} | " +
                $"{Pct(r.Mix.NoteF1)} | {Pct(r.Stemmed.NoteF1)} |"));
        }

        if (notes.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("Not scored:");
            foreach (var n in notes) sb.AppendLine("- " + n);
        }

        return sb.ToString();
    }

    private static string Line(string label, int count, string source, AutoChartScore s) =>
        string.Create(CultureInfo.InvariantCulture,
            $"| {label} | {count} | {source} | {Pct(s.OnsetPrecision)} | {Pct(s.OnsetRecall)} | {Pct(s.OnsetF1)} | " +
            $"{Pct(s.PitchAccuracy)} | {Pct(s.NotePrecision)} | {Pct(s.NoteRecall)} | {Pct(s.NoteF1)} |");
}
