<#
.SYNOPSIS
    Regenerates (or checks) licenses/dependencies.json, the committed inventory
    of every dependency's licence (#828).

.DESCRIPTION
    The `packages` section is derived: every NuGet package in the resolved
    assets (obj/project.assets.json) of every project in the repository, with
    the SPDX licence expression from its .nuspec in the NuGet cache. A package
    whose nuspec has no SPDX expression gets its licence from $Overrides below,
    with the reason; an unresolved one stops the script.

    The `native` section is curated by hand (vendored libraries, the bundled
    tools, the fonts) and is carried over unchanged. Edit it in the JSON file.

    This script may use the network (-Restore); the tests never do: they read
    the committed file and the assets the build already wrote.

.PARAMETER Restore
    Run `dotnet restore` on every project first, so the assets are complete
    (needs the network on a cold cache).

.PARAMETER Check
    Write nothing; exit 1 when the committed file differs from what the assets
    produce. Offline. New-Release.ps1 runs this in preflight.
#>
[CmdletBinding()]
param(
    [switch]$Restore,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..' '..')).Path
$InventoryPath = Join-Path $RepoRoot 'licenses/dependencies.json'
$NuGetRoot = if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $env:USERPROFILE '.nuget/packages' }

# Packages whose nuspec carries no SPDX expression (a licenseUrl or nothing).
# Each entry says where the licence was read, so it can be re-checked.
$Overrides = @{
    'Avalonia.Angle.Windows.Natives'        = @{ License = 'BSD-3-Clause'; Note = 'ANGLE Project licence file in the package' }
    'Microsoft.DotNet.PlatformAbstractions' = @{ License = 'MIT'; Note = 'LICENSE.TXT in the package' }
    'Microsoft.ML.OnnxRuntime.DirectML'     = @{ License = 'MIT'; Note = 'LICENSE in the package' }
    'Microsoft.ML.OnnxRuntime.Managed'      = @{ License = 'MIT'; Note = 'LICENSE.txt in the package' }
    'NVorbis'                               = @{ License = 'MIT'; Note = 'LICENSE in the package' }
    'SQLite'                                = @{ License = 'LicenseRef-Public-Domain'; Note = 'native SQLite (e_sqlite3): public domain, https://sqlite.org/copyright.html' }
}
$Overrides['Microsoft.AI.DirectML'] = @{ License = 'LicenseRef-Microsoft-DirectML-Redistributable'; Note = 'Microsoft DirectML redistributable licence (proprietary); redistributed unmodified beside the app, as that licence permits' }

if ($Restore) {
    Get-ChildItem $RepoRoot -Recurse -Filter *.csproj |
        Where-Object { $_.FullName.Substring($RepoRoot.Length) -notmatch '[\\/](\.claude|\.codex|bin|obj)[\\/]' } |
        ForEach-Object { dotnet restore $_.FullName --nologo -v:q; if ($LASTEXITCODE -ne 0) { throw "restore failed: $($_.FullName)" } }
}

$found = @{}
$assets = Get-ChildItem $RepoRoot -Recurse -Filter project.assets.json |
    Where-Object { $_.FullName.Substring($RepoRoot.Length) -notmatch '[\\/](\.claude|\.codex)[\\/]' }
foreach ($file in $assets) {
    $json = Get-Content $file.FullName -Raw | ConvertFrom-Json
    foreach ($lib in $json.libraries.PSObject.Properties) {
        if ($lib.Value.type -eq 'package') { $found[$lib.Name] = $true }
    }
}
if ($found.Count -eq 0) { throw 'No project.assets.json found: build or restore first (-Restore).' }

$packages = foreach ($key in ($found.Keys | Sort-Object { $_.ToLowerInvariant() })) {
    $id, $version = $key -split '/', 2
    $nuspec = Join-Path $NuGetRoot ("{0}/{1}/{0}.nuspec" -f $id.ToLowerInvariant(), $version)
    if (-not (Test-Path $nuspec)) { throw "$key is not in the NuGet cache ($NuGetRoot): restore first (-Restore)." }
    $meta = ([xml](Get-Content $nuspec -Raw)).package.metadata
    $license = $null
    if ($meta.license -and $meta.license.type -eq 'expression') { $license = [string]$meta.license.'#text' }
    elseif ($Overrides.ContainsKey($id)) { $license = $Overrides[$id].License }
    if (-not $license) {
        throw "$key has no SPDX licence expression (license type '$($meta.license.type)', licenseUrl '$($meta.licenseUrl)'). Read its licence, then add it to `$Overrides in this script."
    }
    $entry = [ordered]@{ id = $id; version = $version; license = $license }
    if ($Overrides.ContainsKey($id)) { $entry.note = $Overrides[$id].Note }
    $entry
}

$native = @()
if (Test-Path $InventoryPath) {
    $native = @((Get-Content $InventoryPath -Raw | ConvertFrom-Json).native)
}
$doc = [ordered]@{
    schema   = 1
    comment  = 'Generated by tools/release/Update-DependencyInventory.ps1 (packages) and curated by hand (native). Checked by DependencyLicenceTests. Licences are SPDX ids; LicenseRef-* ones are reviewed in THIRD-PARTY-NOTICES.md.'
    packages = @($packages)
    native   = $native
}
$text = (($doc | ConvertTo-Json -Depth 6) -replace "`r`n", "`n") + "`n"

if ($Check) {
    $current = if (Test-Path $InventoryPath) { (Get-Content $InventoryPath -Raw) -replace "`r`n", "`n" } else { '' }
    if ($current -ne $text) {
        Write-Error 'licenses/dependencies.json is out of date: run tools/release/Update-DependencyInventory.ps1 and commit it.'
        exit 1
    }
    Write-Host "licenses/dependencies.json is current ($(@($packages).Count) packages)."
    exit 0
}

New-Item -ItemType Directory -Force (Split-Path $InventoryPath) | Out-Null
[IO.File]::WriteAllText($InventoryPath, $text, [Text.UTF8Encoding]::new($false))
Write-Host "Wrote $InventoryPath ($(@($packages).Count) packages, $(@($native).Count) native)."
